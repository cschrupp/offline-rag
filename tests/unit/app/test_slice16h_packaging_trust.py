"""16H-IR-002 — build CA is BuildKit-secret only; never runtime trust policy."""

from __future__ import annotations

import re
import subprocess
import textwrap
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[3]
DOCKERFILE = REPO_ROOT / "deploy" / "Dockerfile"
DOCKERIGNORE = REPO_ROOT / ".dockerignore"
TEST_CA_CN = "OFFLINERAG-16H-TEST-CA-NOT-FOR-RUNTIME"


def test_dockerfile_never_copies_deploy_certs() -> None:
    text = DOCKERFILE.read_text(encoding="utf-8")
    assert "COPY deploy/certs" not in text
    assert re.search(
        r"--mount=type=secret,id=build_ca",
        text,
    )
    # No persistent ENV that would keep a custom CA path in the final image.
    assert "ENV NODE_EXTRA_CA_CERTS" not in text


def test_dockerignore_excludes_build_host_ca_material() -> None:
    text = DOCKERIGNORE.read_text(encoding="utf-8")
    assert "deploy/certs/*.crt" in text
    assert "deploy/certs/*.pem" in text
    assert "deploy/wheelhouse/" in text


def test_dockerfile_keeps_tls_verification_enabled() -> None:
    text = DOCKERFILE.read_text(encoding="utf-8")
    for banned in (
        "PIP_NO_VERIFY",
        "NODE_TLS_REJECT_UNAUTHORIZED=0",
        "--trusted-host",
        "curl -k",
        "ssl._create_unverified_context",
    ):
        assert banned not in text


def test_dockerignore_keeps_local_crt_out_of_build_context(tmp_path: Path) -> None:
    """Prove deploy/certs/*.crt is not present in the Docker build context."""
    certs = REPO_ROOT / "deploy" / "certs"
    certs.mkdir(parents=True, exist_ok=True)
    probe = certs / "16h-context-probe.crt"
    marker = f"{TEST_CA_CN}-CONTEXT-PROBE-MARKER"
    probe.write_text(
        textwrap.dedent(
            f"""\
            -----BEGIN CERTIFICATE-----
            {marker}
            -----END CERTIFICATE-----
            """
        ),
        encoding="utf-8",
    )
    try:
        # Minimal Dockerfile that fails the build if the probe file is visible.
        df = tmp_path / "Dockerfile.context-probe"
        df.write_text(
            textwrap.dedent(
                """\
                # syntax=docker/dockerfile:1.7
                FROM alpine:3.20
                COPY deploy/certs/ /probe/
                RUN if ls /probe/*.crt >/dev/null 2>&1; then \
                      echo 'CONTEXT_LEAK'; ls -la /probe; exit 1; \
                    fi; \
                    echo 'CONTEXT_CLEAN'
                """
            ),
            encoding="utf-8",
        )
        result = subprocess.run(
            [
                "docker",
                "build",
                "--progress=plain",
                "--no-cache",
                "-f",
                str(df),
                "-t",
                "offline-rag:16h-context-probe",
                ".",
            ],
            cwd=str(REPO_ROOT),
            text=True,
            capture_output=True,
            check=False,
        )
        combined = (result.stdout or "") + (result.stderr or "")
        if "Cannot connect to the Docker daemon" in combined or result.returncode == 125:
            pytest.skip("Docker unavailable")
        # Leak path exits 1; success proves *.crt was excluded from context.
        assert result.returncode == 0, combined[-2000:]
        # Match BuildKit RUN echo lines only — Dockerfile script text also
        # contains the literal token CONTEXT_LEAK in the failure branch.
        assert re.search(r"#\d+\s+[\d.]+\s+CONTEXT_CLEAN\b", combined)
        assert not re.search(r"#\d+\s+[\d.]+\s+CONTEXT_LEAK\b", combined)
    finally:
        probe.unlink(missing_ok=True)
        subprocess.run(
            ["docker", "rmi", "-f", "offline-rag:16h-context-probe"],
            cwd=str(REPO_ROOT),
            check=False,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )


def test_runtime_image_trust_store_excludes_custom_build_ca_marker() -> None:
    """If offline-rag:16h-smoke exists, assert test/interception CA CN is absent."""
    inspect = subprocess.run(
        ["docker", "image", "inspect", "offline-rag:16h-smoke"],
        cwd=str(REPO_ROOT),
        capture_output=True,
        text=True,
        check=False,
    )
    if inspect.returncode != 0:
        pytest.skip("offline-rag:16h-smoke image not present")

    markers = (
        TEST_CA_CN,
        "Norton Web/Mail Shield Root",
        "generated by Norton Antivirus for SSL/TLS scanning",
    )
    script = (
        "from pathlib import Path\n"
        "roots = []\n"
        "p = Path('/etc/ssl/certs/ca-certificates.crt')\n"
        "roots.append(p.read_text(encoding='utf-8', errors='replace') if p.is_file() else '')\n"
        "extra = Path('/usr/local/share/ca-certificates')\n"
        "if extra.is_dir():\n"
        "    for f in extra.glob('*.crt'):\n"
        "        roots.append(f.read_text(encoding='utf-8', errors='replace'))\n"
        "blob = '\\n'.join(roots)\n"
        "print('TRUST_BLOB_BYTES', len(blob))\n"
        "for m in " + repr(markers) + ":\n"
        "    if m in blob:\n"
        "        raise SystemExit(f'MARKER_PRESENT:{m}')\n"
        "print('TRUST_STORE_CLEAN')\n"
    )
    probe = subprocess.run(
        ["docker", "run", "--rm", "--entrypoint", "python", "offline-rag:16h-smoke", "-c", script],
        cwd=str(REPO_ROOT),
        text=True,
        capture_output=True,
        check=False,
    )
    out = (probe.stdout or "") + (probe.stderr or "")
    assert probe.returncode == 0, out[-2000:]
    assert "TRUST_STORE_CLEAN" in out
    assert "MARKER_PRESENT" not in out
